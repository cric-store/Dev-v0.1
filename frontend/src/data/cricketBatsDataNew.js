// Helper functions
export const getCricketBatsByBrand = (brandId) => {
  if (brandId === 'all') return cricketBatsNew;
  return cricketBatsNew.filter(bat => bat.brandId === brandId);
};

export const getInStockCricketBats = () => {
  return cricketBatsNew.filter(bat => bat.inStock);
};

export const getCricketBatById = (id) => {
  return cricketBatsNew.find(bat => bat.id === id);
};
